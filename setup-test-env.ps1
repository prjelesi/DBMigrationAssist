#!/usr/bin/env pwsh
<#
.SYNOPSIS
    One-click test environment setup for DBMigrationAssist.
    Installs prerequisites, starts Docker container, validates all endpoints,
    and optionally opens ngrok tunnel for Power Platform connectivity.

.PARAMETER Mode
    "docker"  - Start Docker container only (default)
    "full"    - Docker + ngrok tunnel
    "stop"    - Stop and clean up all containers

.PARAMETER ApiKey
    API key to use (defaults to 'dev-key-change-me' for local testing)

.PARAMETER NgrokToken
    ngrok auth token (required for Mode=full). Get one at https://ngrok.com

.EXAMPLE
    .\setup-test-env.ps1
    .\setup-test-env.ps1 -Mode full -NgrokToken "your-ngrok-token"
    .\setup-test-env.ps1 -Mode stop
#>

param(
    [ValidateSet("docker", "full", "stop")]
    [string]$Mode = "docker",
    [string]$ApiKey = "dev-key-change-me",
    [string]$NgrokToken = ""
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$ProjectRoot = $PSScriptRoot
$DockerDir   = Join-Path $ProjectRoot "docker"
$EnvFile     = Join-Path $DockerDir ".env"

# ── Colors ────────────────────────────────────────────────────────────────────
function Write-Step  { param($m) Write-Host "`n>>> $m" -ForegroundColor Cyan }
function Write-OK    { param($m) Write-Host "  [OK] $m" -ForegroundColor Green }
function Write-Warn  { param($m) Write-Host "  [!]  $m" -ForegroundColor Yellow }
function Write-Fail  { param($m) Write-Host "  [X]  $m" -ForegroundColor Red; throw $m }

# ── STOP mode ─────────────────────────────────────────────────────────────────
if ($Mode -eq "stop") {
    Write-Step "Stopping all DBMigrationAssist containers..."
    docker compose -f "$DockerDir\docker-compose.yml" down --remove-orphans
    Write-OK "Containers stopped."
    exit 0
}

# ── Prerequisites check ───────────────────────────────────────────────────────
Write-Step "Checking prerequisites..."

# Docker
try {
    $dv = docker --version 2>&1
    Write-OK "Docker: $dv"
} catch {
    Write-Fail "Docker not found. Install from https://www.docker.com/products/docker-desktop"
}

# Docker running
try {
    docker info 2>&1 | Out-Null
    Write-OK "Docker daemon is running"
} catch {
    Write-Fail "Docker daemon is not running. Start Docker Desktop first."
}

# PowerShell 7
if ($PSVersionTable.PSVersion.Major -ge 7) {
    Write-OK "PowerShell $($PSVersionTable.PSVersion)"
} else {
    Write-Warn "PowerShell 7+ recommended. Current: $($PSVersionTable.PSVersion)"
}

# ngrok (only if full mode)
if ($Mode -eq "full") {
    try {
        $ngv = ngrok version 2>&1
        Write-OK "ngrok: $ngv"
    } catch {
        Write-Warn "ngrok not found. Installing via winget..."
        winget install ngrok.ngrok --silent
    }
    if (-not $NgrokToken) {
        Write-Fail "-NgrokToken is required for Mode=full. Get one free at https://ngrok.com"
    }
}

# ── Create .env file ──────────────────────────────────────────────────────────
Write-Step "Creating docker/.env..."

if (-not (Test-Path $EnvFile)) {
    $envContent = @"
# Auto-generated by setup-test-env.ps1
# For LOCAL TESTING only - update with real values for production

DATAVERSE_URL=
AZURE_CLIENT_ID=
AZURE_CLIENT_SECRET=
AZURE_TENANT_ID=
API_KEY=$ApiKey
CALLBACK_WEBHOOK_URL=
"@
    $envContent | Out-File $EnvFile -Encoding utf8
    Write-OK "Created docker/.env (Dataverse fields empty - OK for local test)"
} else {
    Write-OK "docker/.env already exists - skipping"
}

# ── Build Docker image ────────────────────────────────────────────────────────
Write-Step "Building Docker image (this takes 3-5 minutes on first run)..."
$buildStart = Get-Date
docker compose -f "$DockerDir\docker-compose.yml" build 2>&1 | ForEach-Object {
    if ($_ -match "error|Error|ERROR") {
        Write-Host "  $_" -ForegroundColor Red
    } elseif ($_ -match "Step|--->" ) {
        Write-Host "  $_" -ForegroundColor DarkGray
    }
}
if ($LASTEXITCODE -ne 0) { Write-Fail "Docker build failed (exit $LASTEXITCODE)" }
$buildTime = [math]::Round(((Get-Date) - $buildStart).TotalSeconds)
Write-OK "Image built in ${buildTime}s"

# ── Start container ───────────────────────────────────────────────────────────
Write-Step "Starting assessment engine container..."
docker compose -f "$DockerDir\docker-compose.yml" up -d
if ($LASTEXITCODE -ne 0) { Write-Fail "docker compose up failed" }

# Wait for health check
Write-Host "  Waiting for API to be ready" -NoNewline
$retries = 0
do {
    Start-Sleep -Seconds 3
    $retries++
    Write-Host "." -NoNewline
    try {
        $health = Invoke-RestMethod -Uri "http://localhost:8000/health" -TimeoutSec 5
        break
    } catch { }
} while ($retries -lt 20)

Write-Host ""
if ($retries -ge 20) { Write-Fail "API did not become healthy after 60 seconds" }
Write-OK "API is healthy: status=$($health.status), version=$($health.version)"

# ── Validate endpoints ────────────────────────────────────────────────────────
Write-Step "Validating API endpoints..."

$headers = @{ "X-API-Key" = $ApiKey }

# GET /questionnaire
try {
    $q = Invoke-RestMethod "http://localhost:8000/questionnaire" -Headers $headers
    Write-OK "GET /questionnaire -> $($q.sections.Count) sections"
} catch { Write-Warn "GET /questionnaire failed: $_" }

# GET /migration-paths
try {
    $mp = Invoke-RestMethod "http://localhost:8000/migration-paths" -Headers $headers
    Write-OK "GET /migration-paths -> $($mp.paths.Count) paths"
} catch { Write-Warn "GET /migration-paths failed: $_" }

# POST /assess with sample data
Write-Step "Running sample assessment (3 databases)..."
$samplePayload = @{
    customerName = "TestCustomer"
    requestedBy  = "setup-test-env.ps1"
    databases    = @(
        @{
            DatabaseName     = "AdventureWorks"
            SourceType       = "SQL Server"
            SourceVersion    = "2019"
            SourceEnvironment = "OnPrem"
            TargetType       = "Azure SQL Database"
            MaxDowntime      = "hours"
            Connectivity     = "vpn"
            LandingZone      = "partial"
            DataSize         = "medium"
            StoredProcs      = "few"
            Dependencies     = ""
            SpecialFeatures  = ""
            TeamSkill        = "moderate"
            RollbackPlan     = "yes_untested"
            DatabaseCount    = 1
        },
        @{
            DatabaseName     = "HRPostgres"
            SourceType       = "PostgreSQL"
            SourceVersion    = "14"
            SourceEnvironment = "AWS_RDS"
            TargetType       = "Azure Database for PostgreSQL Flexible Server"
            MaxDowntime      = "zero"
            Connectivity     = "expressroute"
            LandingZone      = "yes"
            DataSize         = "small"
            StoredProcs      = "none"
            Dependencies     = ""
            SpecialFeatures  = ""
            TeamSkill        = "expert"
            RollbackPlan     = "yes_tested"
            DatabaseCount    = 3
        },
        @{
            DatabaseName     = "OracleFinance"
            SourceType       = "Oracle"
            SourceVersion    = "19c"
            SourceEnvironment = "OnPrem"
            TargetType       = "Azure Database for PostgreSQL Flexible Server"
            MaxDowntime      = "days"
            Connectivity     = "vpn"
            LandingZone      = "no"
            DataSize         = "large"
            StoredProcs      = "extensive"
            Dependencies     = ""
            SpecialFeatures  = "plsql"
            TeamSkill        = "beginner"
            RollbackPlan     = "no"
            DatabaseCount    = 1
        }
    )
} | ConvertTo-Json -Depth 5

try {
    $job = Invoke-RestMethod "http://localhost:8000/assess" -Method POST `
        -Headers ($headers + @{ "Content-Type" = "application/json" }) `
        -Body $samplePayload
    Write-OK "Assessment submitted. JobId: $($job.jobId)"

    # Poll for completion
    Write-Host "  Polling for completion" -NoNewline
    $attempts = 0
    do {
        Start-Sleep -Seconds 5
        $attempts++
        Write-Host "." -NoNewline
        $status = Invoke-RestMethod "http://localhost:8000/status/$($job.jobId)" -Headers $headers
    } while ($status.status -notin @("completed","failed") -and $attempts -lt 24)

    Write-Host ""
    if ($status.status -eq "completed") {
        $report = Invoke-RestMethod "http://localhost:8000/report/$($job.jobId)" -Headers $headers
        Write-OK "Assessment completed! Results:"
        $report | ForEach-Object {
            $band = $_.ReadinessBand
            $score = $_.ReadinessScore
            $name = $_.DatabaseName
            $color = switch ($band) {
                "Ready to Migrate"     { "Green" }
                "Conditionally Ready"  { "Yellow" }
                "Needs Preparation"    { "DarkYellow" }
                default                { "Red" }
            }
            Write-Host ("    [{0,3}/100] {1,-30} [{2}]" -f $score, $name, $band) -ForegroundColor $color
        }
    } else {
        Write-Warn "Assessment status: $($status.status). Error: $($status.error)"
    }
} catch {
    Write-Warn "Assessment test failed: $_"
}

# ── ngrok tunnel (full mode) ──────────────────────────────────────────────────
if ($Mode -eq "full") {
    Write-Step "Starting ngrok tunnel (for Power Platform connectivity)..."
    ngrok config add-authtoken $NgrokToken
    $ngrokProc = Start-Process ngrok -ArgumentList "http 8000 --log=stdout" -PassThru -NoNewWindow
    Start-Sleep -Seconds 4

    try {
        $tunnels = Invoke-RestMethod "http://localhost:4040/api/tunnels"
        $publicUrl = ($tunnels.tunnels | Where-Object { $_.proto -eq "https" } | Select-Object -First 1).public_url
        Write-OK "ngrok public URL: $publicUrl"
        Write-Host ""
        Write-Host "  !! IMPORTANT: Use this URL in your Power Apps Custom Connector:" -ForegroundColor Yellow
        Write-Host "  $publicUrl" -ForegroundColor White
        Write-Host ""
        Write-Host "  Update your Custom Connector host to: $($publicUrl -replace 'https://','')" -ForegroundColor Yellow
    } catch {
        Write-Warn "Could not retrieve ngrok URL. Check http://localhost:4040"
    }
}

# ── Summary ───────────────────────────────────────────────────────────────────
$separator = "=" * 60
Write-Host "`n$separator" -ForegroundColor Cyan
Write-Host "  TEST ENVIRONMENT READY" -ForegroundColor Cyan
Write-Host $separator -ForegroundColor Cyan
Write-Host "  API URL:      http://localhost:8000"
Write-Host "  API Docs:     http://localhost:8000/docs"
Write-Host "  API Key:      $ApiKey"
Write-Host "  Container:    db-migration-assessment"
Write-Host "  Logs:         docker logs db-migration-assessment -f"
if ($Mode -eq "full" -and $publicUrl) {
    Write-Host "  ngrok URL:    $publicUrl"
}
Write-Host $separator -ForegroundColor Cyan
Write-Host "`nTo stop: .\setup-test-env.ps1 -Mode stop`n"
